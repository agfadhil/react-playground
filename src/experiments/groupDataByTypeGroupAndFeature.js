function groupDataByTypeGroupAndFeature(data) {
  // Group by group.type first
  const groupedByType = data.reduce((acc, item) => {
    const groupType = item.group.type;

    if (!acc[groupType]) {
      acc[groupType] = [];
    }

    acc[groupType].push(item);
    return acc;
  }, {});

  // Then group by group.id within each type
  const result = Object.values(groupedByType).map((typeItems, index) => {
    const groupedByGroup = typeItems.reduce((acc, item) => {
      const groupId = item.group.id;

      if (!acc[groupId]) {
        acc[groupId] = {
          id: groupId,
          name: item.group.name,
          status: item.group.status,
          type: item.group.type,
          actions: [],
        };
      }

      acc[groupId].actions.push(item);
      return acc;
    }, {});

    // Then group by feature.id within each group
    const groups = Object.values(groupedByGroup).map((group) => {
      const groupedByFeature = group.actions.reduce((acc, item) => {
        const featureId = item.feature_action.feature.id;

        if (!acc[featureId]) {
          acc[featureId] = {
            id: featureId,
            name: item.feature_action.feature.name,
            url: item.feature_action.feature.url,
            actions: [],
          };
        }

        // Only save the action property and its value
        acc[featureId].actions.push(item.feature_action.action);
        return acc;
      }, {});

      return {
        group: {
          id: group.id,
          name: group.name,
          status: group.status,
          type: group.type,
        },
        features: Object.values(groupedByFeature),
      };
    });

    return {
      type: typeItems[0].group.type,
      type_name: typeItems[0].group.type_name || `Type ${index + 1}`,
      groups: groups,
    };
  });

  return result;
}

